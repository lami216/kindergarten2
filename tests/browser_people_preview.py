            await expect(page.locator('#toast')).to_contain_text('تم اعتماد وحفظ')
            await expect(page.locator('#roll-dialog')).not_to_be_visible()
            await page.screenshot(path=str(out/'teachers-attendance-desktop.png'),full_page=True)
            passed.append('teacher_daily_register_excuse_required_and_persisted')
            await page.locator('nav [data-page="students"]').click()
            await expect(page.locator('#open-student-attendance')).to_be_visible()
            await expect(page.locator('#student-rows .attendance-badge').first).to_be_visible()
            await page.locator('#open-student-attendance').click()
            await page.locator('#start-attendance').click()
            for ident in await page.locator('.roll-person.unmarked [data-roll-status="present"]').evaluate_all('(els)=>els.map(el=>el.dataset.rollPerson)'):await page.locator('[data-roll-person="'+ident+'"][data-roll-status="present"]').click()
            await page.locator('[data-roll-person="1"][data-roll-status="absent"]').click()
            await page.locator('#roll-dialog [data-roll-exit]').click()
            await expect(page.locator('#discard-attendance')).to_be_visible()
            await page.locator('#keep-attendance').click()
            await expect(page.locator('#attendance-form')).to_be_visible()
